import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {resolve,dirname} from 'node:path';

// Serve a complete, matching text client through the existing Vercel API
// rewrite. Recorded audio uses the MP3 files at the Vercel site root.
export function buildLiveClient(root=dirname(fileURLToPath(import.meta.url))) {
  const prefix='/api/slimo/play',assets={};
  let html=readFileSync(resolve(root,'index.html'),'utf8');
  html=html.replace('<head>','<head>\n<base href="/">');
  html=html.replace(/((?:src|href)=")\.\/([^"?#]+\.(?:js|css))("?)/g,(full,before,file,after)=>{
    const body=readFileSync(resolve(root,file),'utf8'),hash=createHash('sha256').update(body).digest('hex').slice(0,16);
    const path='/assets/'+hash+'/'+file;
    assets[path]={body,type:file.endsWith('.css')?'text/css; charset=utf-8':'text/javascript; charset=utf-8'};
    return before+prefix+path+after;
  });
  assets['/']={body:html,type:'text/html; charset=utf-8'};
  return `// Generated by build-live-client.mjs; do not edit.\nconst prefix=${JSON.stringify(prefix)};\nconst assets=${JSON.stringify(assets)};\nexport function serveLiveClient(req) {\n const url=new URL(req.url),path=url.pathname.slice(prefix.length)||'/';\n if(!['GET','HEAD'].includes(req.method))return new Response('Method not allowed',{status:405,headers:{Allow:'GET, HEAD'}});\n const asset=assets[path];if(!asset)return new Response('Not found',{status:404});\n return new Response(req.method==='HEAD'?null:asset.body,{headers:{'Content-Type':asset.type,'Cache-Control':path==='/'?'no-store':'public, max-age=31536000, immutable','X-Content-Type-Options':'nosniff','Cross-Origin-Opener-Policy':'same-origin-allow-popups'}});\n}\n`;
}
if(process.argv[1]&&import.meta.url===pathToFileURL(process.argv[1]).href){
  const source=buildLiveClient();writeFileSync(new URL('./slimo-live-client.generated.js',import.meta.url),source);
  console.log('Built matching live client ('+source.length+' characters).');
}
